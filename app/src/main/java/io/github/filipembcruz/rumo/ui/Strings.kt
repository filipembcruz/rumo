    /** e.g. "34% of a new language", "12 books". */
    fun goalAmount(g: LifeGoal, hours: Double): String {
        val a = g.amount(hours)
        return if (!g.countable) a else when (g) {
            LifeGoal.BOOKS -> t("$a books", "$a livros")
            LifeGoal.FITNESS -> t("$a workouts", "$a treinos")
            LifeGoal.SLEEP -> t("$a nights", "$a noites")
            LifeGoal.FAMILY -> t("$a evenings", "$a noites juntos")
            else -> a
        }
    }

